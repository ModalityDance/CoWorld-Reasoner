ACTIVE_VERIFIER_PROFILE_IDS = (
    "temporal_motion_verifier",
    "viewpoint_layout_verifier",
    "intervention_outcome_verifier",
)

VERIFIER_MODEL_DEFAULTS = {
    "max_tokens": 900,
    "request_timeout": 180,
    "transient_retries": 2,
    "verifier_frame_budget": 9,
}

VERIFIER_TOOL_USAGE_DESCRIPTION = (
    "Purpose: analyze visual evidence generated by the Video World Model in the current Agent "
    "trajectory, after the Main Agent has inspected that generated artifact. Call this only when "
    "a valid generated visual artifact exists and an independent answer-free analysis of one specific visible "
    "relation can add value. Do not use it for original observations alone, generic visual "
    "reasoning, answer selection, option ranking, correctness judgments, or artifact generation."
)


@dataclass
class EvidenceToolContext(GenerationContext):
    verifier_guidance: str = ""
    question: str = ""
    loaded_skill_id: str | None = None
    skill_loads: int = 0
    max_skill_loads: int = 1
    vwm_attempts: int = 0
    max_vwm_attempts: int = 2
    retake_calls: int = 0
    max_retake_calls: int = 1
    single_retake_policy: bool = False


def _profile(profile_id: str) -> VerifierProfile:
    for item in PROFILES:
        if item.profile_id == profile_id:
            return item
    raise ValueError(f"unknown_verifier_profile:{profile_id}")


def _record_media_types(record: dict[str, Any]) -> set[str]:
    output = set()
    for item in record.get("sampled_frames") or []:
        modality = str(item.get("evidence_modality") or "")
        if modality == "video_frame":
            output.add("video")
        elif modality == "generated_image":
            output.add("image")
    return output


def _record_source_tool_interface(record: dict[str, Any]) -> str:
    dispatch = record.get("dispatch") or {}
    tool_interface = str(dispatch.get("tool_interface") or "")
    if tool_interface == RETAKE_TOOL:
        return str(dispatch.get("retake_source_tool_interface") or tool_interface)
    return tool_interface


def _visual_request_context(
    context: EvidenceToolContext,
    record: dict[str, Any],
) -> dict[str, Any]:
    """Build answer-free task context for a verifier's evidence review.

    The verifier needs an operation-level description of the missing visual
    evidence and the preservation constraints. The gap is runtime provenance,
    not a proposed answer or a new agent instruction.
    """

    dispatch = record.get("dispatch") or {}
    indices = [
        int(index)
        for index in dispatch.get("source_image_indices") or []
        if isinstance(index, int) and not isinstance(index, bool)
    ]
    source_roles = [
        str(context.observed_image_roles[index])
        for index in indices
        if 0 <= index < len(context.observed_image_roles)
    ]
    operation_controls = dispatch.get("operation_controls")
    selected_controls = {}
    if isinstance(operation_controls, dict):
        for key in (
            "camera_instruction",
            "target_object",
        ):
            if operation_controls.get(key) is not None:
                selected_controls[key] = operation_controls[key]
    operation = str(dispatch.get("operation") or "").strip()
    if not operation:
        source_tool = _record_source_tool_interface(record)
        operation = {
            "vwm_temporal_interpolation_tool": "temporal_interpolation",
            "vwm_new_view_tool": "view_change",
            "vwm_simulate_intervention_tool": "intervention",
        }.get(source_tool, "")
    payload = {
        "operation": operation,
        "tool_interface": str(dispatch.get("tool_interface") or ""),
        "source_image_indices": indices,
        "source_image_roles": source_roles,
        "information_gap": str(dispatch.get("information_gap") or "").strip()
        or operation_information_gap(operation),
        "generation_instruction": str(
            dispatch.get("generation_instruction") or ""
        ).strip(),
        "preserve": [
            str(item).strip()
            for item in dispatch.get("preserve") or []
            if str(item).strip()
        ],
        "operation_controls": selected_controls,
    }
    evidence_focus = str(dispatch.get("evidence_focus") or "").strip()
    if evidence_focus:
        payload["evidence_focus"] = evidence_focus
    for key in (
        "source_order_mode",
        "reference_image_index",
        "candidate_image_index",
    ):
        value = dispatch.get(key)
        if value is not None:
            payload[key] = value
    if not _answer_free_payload(payload):
        raise ValueError("vwm_verifier_context_answer_leak")
    return payload


def _record_matches_profile(record: dict[str, Any], profile: VerifierProfile) -> bool:
    tool_interface = _record_source_tool_interface(record)
    generation = record.get("generation") or {}
    return bool(
        generation.get("technically_valid") is True
        and record.get("sampled_frames")
        and tool_interface in profile.source_tools
        and _record_media_types(record).intersection(profile.media_types)
    )


def _answer_free_payload(payload: dict[str, Any]) -> bool:
    forbidden = {
        "answer",
        "final_answer",
        "correct_option",
        "selected_option",
        "option_ranking",
        "is_correct",
        "score",
    }
    if forbidden.intersection(payload):
        return False
    text = json.dumps(payload, ensure_ascii=False).lower()
    return not any(
        re.search(pattern, text)
        for pattern in (
            r"\bthe\s+answer\s+is\b",
            r"\bcorrect\s+(option|answer|choice)\b",
            r"\bchoose\s+(option\s+)?[a-d]\b",
            r"\b(option|choice)\s+[a-d]\s+is\s+correct\b",
        )
    )


def _profile_enabled(profile_id: str):
    profile = _profile(profile_id)

    def enabled(wrapper: Any, _agent: Any) -> bool:
        context = wrapper.context
        return bool(
            isinstance(context, EvidenceToolContext)
            and context.verifier_calls < context.max_verifier_calls
            and any(
                _record_matches_profile(record, profile)
                for record in context.valid_media_records
            )
        )

    return enabled


def _retake_enabled(wrapper: Any, _agent: Any) -> bool:
    context = wrapper.context
    if not isinstance(context, EvidenceToolContext):
        return False
    if (
        context.retake_calls >= context.max_retake_calls
        or context.vwm_calls >= context.max_vwm_calls
    ):
        return False
    return bool(context.valid_media_records)


def build_video_retake_tool(*, timeout_seconds: float = 7500.0) -> Any:
    """Repeat one prior VWM-driven tool request with a model-authored evidence focus."""

    from agents import FunctionTool

    required = {"generation_index", "repair_focus", "failure_reasons"}

    async def invoke(wrapper: Any, raw_args: str) -> Any:
        context = wrapper.context
        call_id = str(getattr(wrapper, "tool_call_id", ""))
        if not isinstance(context, EvidenceToolContext):
            raise TypeError("evidence_tool_context_required")
        try:
            args = json.loads(raw_args)
            if not isinstance(args, dict) or set(args) != required:
                raise ValueError("retake_arguments_fields_mismatch")
            generation_index = int(args["generation_index"])
            repair_focus = str(args["repair_focus"]).strip()
            failure_reasons = args["failure_reasons"]
            if not repair_focus:
                raise ValueError("repair_focus_required")
            if (
                not isinstance(failure_reasons, list)
                or not failure_reasons
                or any(
                    not isinstance(item, str) or not item.strip()
                    for item in failure_reasons
                )
            ):
                raise ValueError("failure_reasons_must_be_nonempty_string_array")
            if context.retake_calls >= context.max_retake_calls:
                raise ValueError("retake_budget_exhausted")
            if context.vwm_calls >= context.max_vwm_calls:
                raise ValueError("vwm_call_budget_exhausted")
            selected = next(
                record
                for record in context.valid_media_records
                if int(record.get("generation_index", -1)) == generation_index
            )
            source_dispatch = dict(selected.get("dispatch") or {})
            source_tool = _record_source_tool_interface(selected)
            answer_free_error = _answer_free_violation(
                [repair_focus, *[str(item) for item in failure_reasons]]
            )
            if answer_free_error:
                raise ValueError(answer_free_error)
        except (ValueError, TypeError, StopIteration, json.JSONDecodeError) as exc:
            payload = {
                "tool_name": RETAKE_TOOL,
                "call_id": call_id,
                "status": "invalid_request",
                "error": str(exc),
            }
            context.emit("tool_result", payload)
            return json.dumps(payload, sort_keys=True)

        dispatch = {
            **source_dispatch,
            "dispatch_id": _dispatch_id(context, call_id),
            "tool_interface": RETAKE_TOOL,
            "generation_instruction": (
                f"{source_dispatch['generation_instruction']} Retake the same operation while "
                f"repairing this concrete artifact failure: {repair_focus}"
            ),
            "control_provenance": "agent_model_retake_focus_with_runtime_inherited_route",
            "requested_by_skill_id": selected_skill_id(context),
            "retake_source_generation_index": generation_index,
            "retake_source_tool_interface": source_tool,
            "retake_source_dispatch_id": source_dispatch.get("dispatch_id"),
            "repair_focus": repair_focus,
            "failure_reasons": [str(item).strip() for item in failure_reasons],
        }
        context.retake_calls += 1
        context.vwm_calls += 1
        context.accepted_dispatches.append(dispatch)
        context.emit(
            "planning",
            {
                "tool_name": RETAKE_TOOL,
                "call_id": call_id,
                "selected_skill": selected_skill_id(context),
                "retake_source_generation_index": generation_index,
                "repair_focus": repair_focus,
            },
        )
        context.emit("vwm_call", {"call_id": call_id, **dispatch})
        return execute_generation_request(context, dispatch, call_id)

    return FunctionTool(
        name=RETAKE_TOOL,
        description=(
            "After inspecting one generated visual artifact, repeat "
            "the same VWM-driven tool request for a specific repairable identity, continuity, framing, "
            "control-following, or coverage failure. The runtime inherits the prior source, operation, "
            "controls, and backend; change only the model-authored repair focus."
        ),
        params_json_schema={
            "type": "object",
            "additionalProperties": False,
            "required": sorted(required),
            "properties": {
                "generation_index": {"type": "integer", "minimum": 0},
                "repair_focus": {"type": "string", "minLength": 1},
                "failure_reasons": {
                    "type": "array",
                    "minItems": 1,
                    "maxItems": 6,
                    "items": {"type": "string", "minLength": 1},
                },
            },
        },
        on_invoke_tool=invoke,
        strict_json_schema=True,
        is_enabled=_retake_enabled,
        timeout_seconds=timeout_seconds,
        timeout_behavior="error_as_result",
    )


def build_verifier_tool(
    profile_id: str,
    *,
    timeout_seconds: float = 600.0,
) -> Any:
    from agents import FunctionTool

    profile = _profile(profile_id)
    if profile_id not in ACTIVE_VERIFIER_PROFILE_IDS:
        raise ValueError(f"inactive_verifier_profile:{profile_id}")
    required = {"generation_index", "question_focus"}

    async def invoke(wrapper: Any, raw_args: str) -> str:
        context = wrapper.context
        call_id = str(getattr(wrapper, "tool_call_id", ""))
        if not isinstance(context, EvidenceToolContext):
            raise TypeError("evidence_tool_context_required")
        try:
            args = json.loads(raw_args)
            if not isinstance(args, dict) or set(args) != required:
                raise ValueError("verifier_profile_arguments_fields_mismatch")
            generation_index = int(args["generation_index"])
            question_focus = str(args["question_focus"]).strip()
            if not question_focus:
                raise ValueError("question_focus_required")
            answer_free_error = _answer_free_violation([question_focus])
            if answer_free_error:
                raise ValueError(answer_free_error)
            selected = next(
                record
                for record in context.valid_media_records
                if record.get("generation_index") == generation_index
                and _record_matches_profile(record, profile)
            )
        except (ValueError, TypeError, StopIteration, json.JSONDecodeError) as exc:
            payload = {
                "tool_name": profile_id,
                "call_id": call_id,
                "status": "invalid_request",
                "error": str(exc),
            }
            context.emit("tool_result", payload)
            return json.dumps(payload, sort_keys=True)

        context.verifier_calls += 1
        from runtime.media_context import predicted_evidence_id

        predicted = [
            {
                "path": item["path"],
                "evidence_id": predicted_evidence_id(generation_index, index),
                "source_type": "predicted_vwm_frame",
                "evidence_modality": item["evidence_modality"],
                "frame_index_in_video": item["frame_index"],
                "artifact_ref": item["artifact_path"],
                "oracle_status": "predicted_not_oracle",
            }
            for index, item in enumerate(selected["sampled_frames"])
        ]
        manifest = predicted
        controls = {
            "generation_index": generation_index,
            "artifact_refs": [item["path"] for item in manifest],
            "attachment_manifest": manifest,
            "visual_request_context": _visual_request_context(context, selected),
            "question_focus": question_focus,
            "verifier_profile": profile_id,
            "observation_schema": "generated_evidence_observations_v2",
            "answer_free": True,
            "reasoning_effort": "medium",
        }
        controls.update(VERIFIER_MODEL_DEFAULTS)
        controls.update(
            {
                "task_question": context.question,
                "observation_guidance": context.verifier_guidance,
            }
        )
        request = ToolRequest(
            tool_interface="video_verifier_tool",
            input_evidence_ids=[item["evidence_id"] for item in manifest],
            request_id=(
                f"vwm_harness/{profile_id}/"
                + hashlib.sha256(
                    (call_id or str(context.verifier_calls)).encode()
                ).hexdigest()[:20]
            ),
            controls=controls,
            constraints={
                "answer_free_generated_observations_only": True,
                "no_answer_label_in_request": True,
                "no_option_ranking_or_correctness_claim": True,
                "predicted_evidence_not_oracle": True,
            },
            requested_by_skill_id=str(selected_skill_id(context) or ""),
            permission_policy={"deny_if_answer_label_in_request": True},
        )
        result = verify_generated_video(request)
        observations = (result.quality or {}).get("observations")
        payload = {
            "tool_name": profile_id,
            "call_id": call_id,
            "status": result.status,
            "generation_index": generation_index,
            "answer_free": True,
            "provenance_label": result.provenance_label,
            "overall_usability": (result.quality or {}).get("overall_usability"),
            "observations": observations,
            "failure_modes": list(result.failure_modes),
            "provider_usage": (result.raw_backend_metadata or {}).get("provider_usage"),
        }
        model_payload = _compact_verifier_payload(
            status=result.status,
            observations=observations,
            failure_modes=list(result.failure_modes),
            quality_check=(result.quality or {}).get("observation_validation"),
        )
        context.verifier_records.append(
            {
                "profile_id": profile_id,
                "request": asdict(request),
                "result": asdict(result),
                "verifier_payload": payload,
                "model_visible_payload": model_payload,
            }
        )
        context.emit("verifier_result", payload)
        context.emit("tool_result", payload)
        return json.dumps(model_payload, ensure_ascii=False, sort_keys=True)

    return FunctionTool(
        name=profile_id,
        description=(
            f"{VERIFIER_TOOL_USAGE_DESCRIPTION} Review one generated artifact for the requested visual relation using "
            f"{profile_id}. {profile.purpose} After inspecting generated media, call this before "
            "finalizing whenever the media contributes to the judgment, unless the original "
            "observations already completely resolve the relation or the media is clearly unusable. "
            "The verifier receives generated visual evidence only, not the original images. "
            "Return a concise answer-free visual comment with visible support and uncertainty; "
            "do not manage the artifact or select an answer."
        ),
        params_json_schema={
            "type": "object",
            "additionalProperties": False,
            "required": sorted(required),
            "properties": {
                "generation_index": {"type": "integer", "minimum": 0},
                "question_focus": {"type": "string", "minLength": 1},
            },
        },
        on_invoke_tool=invoke,
        strict_json_schema=True,
        is_enabled=_profile_enabled(profile_id),
        timeout_seconds=timeout_seconds,
        timeout_behavior="error_as_result",
    )


def _compact_verifier_payload(
    *,
    status: str,
    observations: Any,
    failure_modes: list[str],
    quality_check: Any = None,
) -> dict[str, Any]:
    """Return generated-frame observations for autonomous evidence integration."""
    from evolved_harness.verifier_observations import compact_verifier_observations, INTEGRATION_GUIDANCE

    observation = observations if isinstance(observations, dict) else {}
    return compact_verifier_observations(
        observation,
        status=status,
        failure_modes=failure_modes,
        quality_check=quality_check,
        guidance=INTEGRATION_GUIDANCE,
    )
