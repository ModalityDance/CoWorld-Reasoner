"""Generated-frame observations for the main agent's autonomous evidence use."""

from __future__ import annotations

import json
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, ValidationError


VERIFIER_SCHEMA_VERSION = "generated_evidence_observations_v2"
INTEGRATION_GUIDANCE = (
    "This review describes a generated prediction, not a new real-world observation or "
    "an answer verdict. Combine its visible cues and limitations with the original "
    "observations and the retained trajectory. The Agent may maintain or revise its "
    "working answer through that combined reasoning; no review status dictates the result."
)


class VerifierFinding(BaseModel):
    model_config = ConfigDict(extra="forbid", strict=True)
    finding: str = Field(min_length=1)
    sources: list[str] = Field(min_length=1)
    uncertainty: str


class VerifierObservations(BaseModel):
    model_config = ConfigDict(extra="forbid", strict=True)
    schema_version: Literal["generated_evidence_observations_v2"]
    summary: str = Field(min_length=1)
    request_execution: VerifierFinding
    observations: list[VerifierFinding] = Field(min_length=1, max_length=4)
    defects: list[VerifierFinding] = Field(max_length=3)
    limitations: str


def build_verifier_prompt(controls, manifest):
    context = {
        "task_question": controls.get("task_question"),
        "question_focus": controls.get("question_focus"),
        "observation_guidance": controls.get("observation_guidance", ""),
        "visual_request_context": controls.get("visual_request_context"),
        "attachment_manifest": manifest,
    }
    return (
        "Analyze one video generated by the Video World Model, not the task answer. Read all supplied "
        "sampled frames in temporal order, including the endpoints. The original images are "
        "deliberately not attached; do not claim to compare against or verify them. Use the actual "
        "generation request as context. Describe what visibly changes, whether "
        "the requested action occurs, and which identities or landmarks persist. Use the "
        "question only to identify relevant targets and its stated reference or conditions. "
        "Do not replace a task-given condition with an inferred one. Distinguish camera motion "
        "from object motion and describe the reference when reporting a direction.\n"
        "Describe visible generated changes without assuming facts from unseen originals. "
        "Generated frames remain predictions, not new real-world observations. "
        "An endpoint supplied to generation is a condition, not independent confirmation. "
        "Flag a request that assumes an outcome not given by the task. List only concrete "
        "generation defects or departures from the request in defects; an unresolved answer "
        "or an offscreen target alone is not a broken video. An empty defects list is allowed.\n"
        "Do not choose or rank options, judge correctness, rate whether evidence permits an "
        "answer change, or prescribe the final answer. The main Agent integrates the observations. "
        "Cite exact attached evidence IDs for each finding. Keep each finding to one short "
        "sentence, at most four observations and three defects. Use uncertainty='' when "
        "there is no additional uncertainty. Return only JSON matching this schema:\n"
        + json.dumps(VerifierObservations.model_json_schema(), sort_keys=True)
        + "\nRuntime context:\n"
        + json.dumps(context, sort_keys=True, ensure_ascii=False)
    )


def validate_verifier_observations(parsed, controls):
    reasons = []
    try:
        observation = VerifierObservations.model_validate(parsed)
        known = {
            item["evidence_id"] for item in controls.get("attachment_manifest", [])
            if isinstance(item, dict) and item.get("evidence_id")
        }
        findings = [observation.request_execution, *observation.observations, *observation.defects]
        unknown = sorted({source for row in findings for source in row.sources} - known)
        if unknown:
            reasons.append("unknown_attachment_sources:" + ",".join(unknown))
    except ValidationError as exc:
        reasons.extend(
            "invalid_observation_field:" + ".".join(str(key) for key in error["loc"])
            for error in exc.errors(include_input=False, include_url=False)
        )
    return {
        "is_usable": not reasons, "low_quality_reasons": reasons,
    }


def compact_verifier_observations(parsed, *, status, failure_modes, quality_check, guidance):
    quality_check = quality_check if isinstance(quality_check, dict) else {}
    valid = status == "success" and quality_check.get("is_usable", True) is not False
    if not valid:
        issue_codes = sorted({
            str(item).split(":", 1)[0][:120]
            for item in [
                *failure_modes,
                *(quality_check.get("low_quality_reasons") or []),
            ]
            if str(item).strip()
        })
        return {
            "schema_version": VERIFIER_SCHEMA_VERSION,
            "review_status": status,
            "review_validity": "invalid",
            "overall_usability": "review_invalid",
            "comments": "The verifier review was invalid; no findings were admitted as evidence.",
            "request_execution": None,
            "findings": [],
            "defects": [],
            "limitations": "No verifier claim from this invalid review should be used.",
            "review_issues": {"is_usable": False, "issue_codes": issue_codes},
            "failure_modes": issue_codes,
            "integration_guidance": (
                "Ignore this invalid review and reason from the original observations and "
                "model-visible generated frames."
            ),
        }
    rows = [
        {key: row.get(key) for key in ("finding", "sources", "uncertainty")}
        for row in parsed.get("observations", []) if isinstance(row, dict)
    ] if isinstance(parsed.get("observations"), list) else []
    return {
        "schema_version": VERIFIER_SCHEMA_VERSION,
        "review_status": status,
        "review_validity": "valid" if status == "success" else "invalid",
        "overall_usability": "review_available" if status == "success" else "review_invalid",
        "comments": parsed.get("summary", ""),
        "request_execution": parsed.get("request_execution"),
        "findings": rows,
        "defects": parsed.get("defects", []),
        "limitations": parsed.get("limitations", ""),
        "review_issues": quality_check,
        "failure_modes": list(failure_modes),
        "integration_guidance": guidance,
    }
